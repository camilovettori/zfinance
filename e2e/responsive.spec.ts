import { expect, test, type Page } from '@playwright/test'

const dashboard = (page: Page) => page.getByRole('region', { name: 'Mobile household dashboard' })
  .or(page.getByRole('heading', { name: /^Good / })).first()

async function loadSampleHousehold(page: Page) {
  await page.goto('/')
  const setup = page.getByRole('heading', { name: "Let's set up your household plan" })
  const loadedDashboard = dashboard(page)
  await setup.or(loadedDashboard).first().waitFor({ state: 'visible' })
  if (await setup.isVisible()) await page.getByRole('button', { name: 'Load sample data' }).click()
  await expect(loadedDashboard).toBeVisible()
}

for (const viewport of [
  { width: 320, height: 568 },
  { width: 360, height: 640 },
  { width: 390, height: 844 },
  { width: 430, height: 932 },
  { width: 768, height: 1024 },
]) {
  test(`mobile shell and Planner fit ${viewport.width}x${viewport.height}`, async ({ page }, testInfo) => {
    await page.setViewportSize(viewport)
    await loadSampleHousehold(page)
    await expect(page.locator('.app-topbar')).not.toContainText('Dashboard')
    await expect(page.locator('.app-topbar')).not.toContainText('Our Home')
    await expect(page.locator('.app-topbar').getByRole('img', { name: 'HomeCoin' })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Hide money values' })).toBeVisible()
    if (viewport.width === 390) await page.screenshot({ path: testInfo.outputPath('home-brand-mobile.png') })
    await expect(page.getByText('Available now')).toBeVisible()
    await expect(page.getByText('After tomorrow')).toBeVisible()
    await expect(page.getByText(/Safe to spend|Committed first|Then income/i)).toHaveCount(0)
    await expect(page.locator('.app-sidebar')).toHaveCount(0)
    await expect(page.getByRole('navigation', { name: 'Mobile navigation' })).toBeVisible()
    await expect(page.getByRole('navigation', { name: 'Mobile navigation' }).getByRole('button', { name: 'Bills', exact: true })).toHaveCount(0)
    await expect(page.getByRole('navigation', { name: 'Mobile navigation' }).getByRole('button')).toHaveCount(4)
    await page.getByRole('button', { name: 'Planner' }).click()
    await expect(page.getByRole('region', { name: 'Mobile financial planner' })).toBeVisible()
    await expect(page.getByRole('tab', { name: 'Week' })).toHaveAttribute('aria-selected', 'true')
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)
    expect(overflow).toBeLessThanOrEqual(1)
    if (viewport.width === 320 || viewport.width === 390) await page.screenshot({ path: testInfo.outputPath('mobile-week.png'), fullPage: true })
  })
}

