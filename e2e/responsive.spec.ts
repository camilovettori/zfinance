test('mobile quick entry keeps the selected date, traps focus, saves cents and completes in place', async ({ page }, testInfo) => {
  await page.clock.setFixedTime(new Date('2026-11-03T12:00:00'))
  await page.setViewportSize({ width: 360, height: 640 })
  await loadSampleHousehold(page)
  await page.getByRole('button', { name: 'Planner', exact: true }).click()
  await page.getByRole('tab', { name: 'Month', exact: true }).click()
  await page.getByRole('button', { name: 'Next planner month' }).click()
  await page.locator('.planner-month-day[data-date="2026-12-01"]').click()
  await page.getByRole('button', { name: 'Add income or bill', exact: true }).click()
  const sheet = page.getByRole('dialog', { name: 'Add income or bill', exact: true })
  await expect(sheet).toBeVisible()
  await expect(sheet.getByRole('button', { name: 'Continue', exact: true })).toBeDisabled()
  for (const key of ['1', '2', '.', '3', '4']) await sheet.getByRole('button', { name: key, exact: true }).click()
  await sheet.getByRole('button', { name: 'Close quick entry' }).focus()
  await page.keyboard.press('Shift+Tab')
  await expect(sheet.getByRole('button', { name: 'Scan receipt photo', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(sheet.getByRole('button', { name: 'Close quick entry' })).toBeFocused()
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('hidden')
  await page.screenshot({ path: testInfo.outputPath('mobile-quick-entry.png'), fullPage: true })
  await sheet.getByRole('button', { name: 'Continue', exact: true }).click()
  const form = page.getByRole('dialog', { name: 'Add item', exact: true })
  await expect(form.getByLabel('Amount', { exact: true })).toHaveValue('12.34')
  await expect(form.getByLabel('Due date', { exact: true })).toHaveValue('2026-12-01')
  await form.getByLabel('Name', { exact: true }).fill('Mobile coffee')
  await form.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(form).toHaveCount(0)
  expect(await page.evaluate(() => document.body.style.overflow)).not.toBe('hidden')
  await page.getByRole('tab', { name: 'Day', exact: true }).click()
  await expect(page.locator('.mobile-planner-day-detail')).toHaveAttribute('data-date', '2026-12-01')
  await page.getByRole('button', { name: 'Mark Mobile coffee paid', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Mark Mobile coffee paid', exact: true })).toHaveCount(0)
  await expect(page.locator('.mobile-planner-item').filter({ hasText: 'Mobile coffee' }).getByText('Paid', { exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('mobile-day-paid.png'), fullPage: true })
  await page.getByRole('button', { name: 'More sections' }).click()
  await expect(page.getByRole('dialog', { name: 'More sections' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: 'More sections' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'More sections' })).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(1)
})

